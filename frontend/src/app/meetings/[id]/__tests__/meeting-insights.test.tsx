import { render, screen, fireEvent, waitFor } from "@testing-library/react";
import { vi, test, expect } from "vitest";
import { meetingInsights, type InsightDraft } from "@/lib/api";
import MeetingInsights from "../meeting-insights";
vi.mock("@/lib/api", () => ({ meetingInsights: vi.fn() }));
const draft: InsightDraft = { version: 1, status: "awaiting_review", provider: "mock", summary: "Mock notes", actions: [{ text: "Prepare demo", source_quote: "We will prepare demo", owner: null, deadline: null, status: "pending_confirmation" }], decisions: [] };
test("generate, edit, confirm, save and lock persisted confirmation", async () => {
  vi.mocked(meetingInsights).mockResolvedValueOnce(null).mockResolvedValueOnce(draft).mockImplementationOnce(async (_id, _t, _m, body) => ({ ...body!, version: 2 }));
  render(<MeetingInsights meetingId="m1" token="offline" canEdit />);
  fireEvent.click(await screen.findByText("Analyze saved transcript (mock)"));
  await screen.findByDisplayValue("Prepare demo");
  expect(screen.getByText("Source: We will prepare demo")).toBeInTheDocument();
  fireEvent.change(screen.getByLabelText("Owner"), { target: { value: "reviewer@example.test" } });
  fireEvent.change(screen.getByRole("combobox"), { target: { value: "confirmed" } });
  expect(screen.getByLabelText("Owner")).not.toBeDisabled();
  fireEvent.click(screen.getByText("Save review and confirmations"));
  await waitFor(() => expect(screen.getByLabelText("Owner")).toBeDisabled());
  expect(vi.mocked(meetingInsights).mock.calls[2][3]?.actions[0].status).toBe("confirmed");
});
test("viewer is readonly and failed saves preserve edits", async () => {
  vi.mocked(meetingInsights).mockResolvedValue(draft);
  const { unmount } = render(<MeetingInsights meetingId="m1" token="offline" canEdit={false} />);
  expect(await screen.findByDisplayValue("Mock notes")).toBeDisabled();
  expect(screen.queryByText("Save review and confirmations")).not.toBeInTheDocument(); unmount();
  vi.mocked(meetingInsights).mockResolvedValueOnce(draft).mockRejectedValueOnce(new Error("409"));
  render(<MeetingInsights meetingId="m1" token="offline" canEdit />);
  fireEvent.change(await screen.findByLabelText("Analysis summary"), { target: { value: "Human edits" } });
  fireEvent.click(screen.getByText("Save review and confirmations"));
  await screen.findByRole("alert");
  expect(screen.getByLabelText("Analysis summary")).toHaveValue("Human edits");
});
